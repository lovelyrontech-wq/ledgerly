import { expect, test } from "@playwright/test";
test("chat in browser", async ({ page }) => {
  test.setTimeout(300_000);
  page.on("console", (m) => console.log("CONSOLE", m.type(), m.text()));
  page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
  page.on("requestfailed", (r) => console.log("REQFAILED", r.url(), r.failure()?.errorText));
  await page.goto("/login");
  await page.getByLabel("Email").fill("alice@ledgerly.test");
  await page.getByLabel("Password").fill("demo1234");
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.getByRole("main").getByRole("link", { name: /Q3/ }).first().click();
  const panel = page.getByRole("complementary", { name: "Assistant" });
  await panel.getByLabel("Message").fill("hi");
  await panel.getByRole("button", { name: "Send" }).click();
  await page.waitForTimeout(3000);
  console.log("AFTER 3s:", (await panel.innerText()).slice(0, 600));
  await expect(panel.getByRole("button", { name: "Send" })).toBeVisible({ timeout: 240_000 });
  console.log("FINAL:", (await panel.innerText()).slice(0, 1200));
  await page.screenshot({ path: process.env.SHOT!, fullPage: true });
});
